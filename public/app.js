async function importOldHtmlFile(input) {
  const file = input.files && input.files[0];
  if (!file) return;
  try {
    const html = await file.text();
    const result = await api('/api/import-old-html', { method: 'POST', body: JSON.stringify({ html }) });
    companies = await api('/api/companies');
    if (current) current = await api('/api/company/' + current.inn);
    renderCompanies(); render();
    alert(`Импорт завершен. Обновлено карточек: ${result.updated}`);
  } catch (e) { alert(e.message); }
  finally { input.value = ''; }
}

