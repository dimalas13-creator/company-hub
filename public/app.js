async function api(url, opts = {}) {
  const r = await fetch(url, { headers: { 'Content-Type': 'application/json' }, ...opts });
  const j = await r.json().catch(() => ({}));
  if (!r.ok) throw new Error(j.error || 'Ошибка запроса');
  return j;
}

function applyTheme(theme) {
  const value = theme === 'dark' ? 'dark' : 'light';
  document.documentElement.setAttribute('data-theme', value);
  localStorage.setItem('theme', value);
  document.querySelectorAll('.theme-choice').forEach(b => b.classList.toggle('active', b.dataset.theme === value));
}

function setTheme(theme) { applyTheme(theme); }

function toggleTheme() {
  const currentTheme = document.documentElement.getAttribute('data-theme') || 'light';
  applyTheme(currentTheme === 'dark' ? 'light' : 'dark');
}

async function login(e) {
  e.preventDefault();
  $('loginError').textContent = '';
  try {
    await api('/api/login', { method: 'POST', body: JSON.stringify({ login: $('loginName').value, password: $('loginPass').value }) });
    await boot();
  } catch (err) {
    $('loginError').textContent = err.message;
  }
}

async function logout() { await api('/api/logout', { method: 'POST' }); location.reload(); }

async function boot() {
  applyTheme(localStorage.getItem('theme') || 'light');
  const me = await api('/api/me');
  if (!me.user) return;
  $('login').classList.add('hidden');
  $('app').classList.remove('hidden');
  companies = await api('/api/companies');
  renderCompanies();
  if (companies[0]) selectCompany(companies[0].inn);
}

function renderCompanies() {
  const q = ($('search').value || '').toLowerCase();
  $('list').innerHTML = companies
    .filter(c => (String(c.name || '') + String(c.inn || '') + String(c.ogrn || '')).toLowerCase().includes(q))
    .map(c => `<div class="company ${current && current.inn === c.inn ? 'active' : ''}" onclick="selectCompany('${c.inn}')"><b>${c.sort || ''}. ${c.name}</b><span>ИНН: ${c.inn}${c.ogrn ? ', ОГРН: ' + c.ogrn : ''}</span></div>`)
    .join('');
}

async function selectCompany(inn) {
  try {
    current = await api('/api/company/' + inn);
    renderCompanies();
    render();
  } catch (e) {
    alert(e.message);
  }
}

function tab(t) {
  currentTab = t;
  document.querySelectorAll('.tabs button').forEach(b => b.classList.toggle('active', b.dataset.tab === t));
  render();
}

function val(v) { return v && String(v).trim() ? v : '—'; }
function row(label, value) { return `<div class="row"><div class="label">${label}</div><div class="copyable" onclick="copyText(this)">${val(value)}</div></div>`; }
function copyText(el) { const text = el.textContent.trim(); if (text && text !== '—') navigator.clipboard?.writeText(text); }

function render() {
  if (!current) return;
  $('title').textContent = `${current.name} — ${currentTab.toUpperCase()}`;
  if (currentTab === 'card') return renderCard();
  if (currentTab === 'attorney') return renderAttorney();
  if (currentTab === 'fssp') return renderLink('ФССП', `/api/company/${current.inn}/fssp-link`);
  if (currentTab === 'fns') return renderLink('ФНС / Прозрачный бизнес', `/api/company/${current.inn}/fns-link`);
}

