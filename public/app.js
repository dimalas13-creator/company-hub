function saveAttorneyDraft() {
  const ids = ['af','bd','bp','pp','by','pd','code','valid'];
  ids.forEach(id => { const el = $(id); if (el) attorneyDraft[id] = el.value; });
  localStorage.setItem('attorneyDraft', JSON.stringify(attorneyDraft));
}

function restoreAttorneyDraft() {
  Object.entries(attorneyDraft).forEach(([id, value]) => { const el = $(id); if (el) el.value = value; });
}

function resetAttorneyDraft() {
  attorneyDraft = {};
  localStorage.removeItem('attorneyDraft');
  ['af','bd','bp','pp','by','pd','code','valid'].forEach(id => { const el = $(id); if (el) el.value = ''; });
  updateAttorney();
}

